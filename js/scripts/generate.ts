/**
 * Regenerate `src/generated/` from the schema at the repository root.
 *
 * The repository holds one schema version, a directory `schema/<version>/`
 * with the one document `timetoshare.schema.json`.
 *
 * Three files are produced: `types.ts`, the TypeScript types derived with
 * json-schema-to-typescript from the document, each definition holding a
 * default joined by its complete form; `schema.ts`, the document
 * itself as a constant, so that the package bundles the schema without a JSON
 * import; and `font.ts`, the metrics of the bundled font
 * (`fonts/dejavu-sans-2.37.metrics.json`) as a constant. The test suite
 * re-runs this module and fails when the committed files differ from a fresh
 * generation.
 *
 *     node scripts/generate.ts
 */

import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));

export const schemaDirectory = resolve(here, "../../schema");
export const generatedDirectory = resolve(here, "../src/generated");
const metricsPath = resolve(here, "../../fonts/dejavu-sans-2.37.metrics.json");

const VERSION_DIRECTORY = /^\d+\.\d+\.\d+$/;

/** The name of the schema document inside its version directory. */
export const DOCUMENT = "timetoshare.schema.json";

/**
 * Return the path of the schema document relative to `schema/`: the one
 * version directory's `timetoshare.schema.json`.
 *
 * @throws {Error} unless `schema/` holds exactly one version directory.
 */
export function schemaSource(): string {
  const versions = readdirSync(schemaDirectory).filter(
    (name) =>
      VERSION_DIRECTORY.test(name) && statSync(resolve(schemaDirectory, name)).isDirectory(),
  );
  if (versions.length !== 1) {
    throw new Error(`expected one schema version in ${schemaDirectory}, found ${versions.length}`);
  }
  return `${versions[0]}/${DOCUMENT}`;
}

function readDocument(path: string): Record<string, unknown> {
  return JSON.parse(readFileSync(resolve(schemaDirectory, path), "utf8")) as Record<
    string,
    unknown
  >;
}

function banner(source: string): string {
  return `// Generated by scripts/generate.ts from schema/${source}. Do not edit.`;
}

/**
 * Render the TypeScript types of the schema document.
 *
 * The root type is `Manifest`, and every definition joins under its own
 * name. Objects take only their declared properties
 * (`additionalProperties: false` for generation), so a misspelt key is a
 * compile error, while `Meta`, the one free object, which declares
 * `additionalProperties: true`, stays free. Every definition that
 * states a default, or refers to one that does, joins a second time as its
 * complete form (`CompleteManifest`, `CompleteTimeline`, …, see
 * `completeDefinitions`), and `LosslessManifest` closes the file.
 */
export async function renderTypes(source: string): Promise<string> {
  const document = readDocument(source);
  const definitions = { ...(document.$defs as Record<string, Node>) };
  const { Manifest: root, ...rest } = definitions;
  if (root === undefined) throw new Error("the schema defines no Manifest");
  const complete = completeDefinitions(definitions);
  const view = schemaForTypes({ ...root, title: "Manifest", $defs: { ...rest, ...complete } });
  const prepared = view.$defs as Record<string, Node>;
  for (const name of Object.keys(complete)) {
    // The one member of an `allOf` renders as a type alias, not an interface:
    // an object type alias, like every `Lossless` type, is assignable to an
    // index-signature type such as a JSON object, and an interface is not.
    const { description, ...form } = prepared[name] as Node;
    prepared[name] = { description, allOf: [form] };
  }
  const types = await compile(view, "Manifest", {
    bannerComment: `${banner(source)}\n\nimport type { JsonNumber, Lossless } from "../json/value.js";`,
    additionalProperties: false,
    declareExternallyReferenced: true,
    unreachableDefinitions: true,
  });
  return `${types}${LOSSLESS}`;
}

const LOSSLESS = `/**
 * A manifest as \`parseJson\` reads it: every number a \`JsonNumber\`, every
 * Fraction a pair.
 */
export type LosslessManifest = Lossless<Manifest>;
`;

type Node = Record<string, unknown>;

/**
 * The keys whose default the schema states in prose, not as a `default`
 * keyword, by definition: a timeline's number type defaults to its unit's,
 * so no one value can be its keyword.
 */
const STATED_DEFAULTS: Readonly<Record<string, readonly string[]>> = {
  Timeline: ["number_type"],
};

const COMPLETE = "Complete";
const REFERENCE = "#/$defs/";

/** Every `$ref` target below a node, by definition name. */
function referencesOf(node: unknown, found = new Set<string>()): Set<string> {
  if (Array.isArray(node)) {
    for (const item of node) referencesOf(item, found);
  } else if (typeof node === "object" && node !== null) {
    const { $ref: reference } = node as Node;
    if (typeof reference === "string") found.add(reference.slice(REFERENCE.length));
    for (const value of Object.values(node)) referencesOf(value, found);
  }
  return found;
}

/** Whether a property below a node has a default, as `defaulted` decides. */
function statesDefault(node: unknown, defaulted: (member: unknown) => boolean): boolean {
  if (Array.isArray(node)) return node.some((item) => statesDefault(item, defaulted));
  if (typeof node !== "object" || node === null) return false;
  const { properties } = node as Node;
  if (typeof properties === "object" && properties !== null) {
    if (Object.values(properties as Node).some(defaulted)) return true;
  }
  return Object.values(node).some((value) => statesDefault(value, defaulted));
}

/** Whether a node below a node is typed a number or an integer. */
function holdsNumber(node: unknown): boolean {
  if (Array.isArray(node)) return node.some(holdsNumber);
  if (typeof node !== "object" || node === null) return false;
  const { type } = node as Node;
  const types = Array.isArray(type) ? type : [type];
  if (types.includes("number") || types.includes("integer")) return true;
  return Object.values(node).some(holdsNumber);
}

const NUMBER_TYPES: Readonly<Record<string, string>> = {
  number: "JsonNumber",
  integer: "JsonNumber",
  null: "null",
  string: "string",
  boolean: "boolean",
};

/**
 * The complete forms of the definitions, each named `Complete<name>`.
 *
 * A definition has a complete form when one of its properties has a
 * `default`, stated on the property or on the definition it refers to (a
 * name's `Name`, a `meta`'s `Meta`), or a default `STATED_DEFAULTS` names,
 * or when it refers to a
 * definition that has one. In a complete form every property with a
 * default is required, at every depth; a default stated only in an
 * `if`/`then`/`else` arm (a flow-control element's repeat count, on a
 * repeat_end only) leaves its property optional, as the generation view
 * drops the arms; a property whose default is "absent" (it states none, as
 * a manifest's `id` and `graphical` and a root's `offset`) stays optional. Numbers are typed as `parseJson` reads
 * them: a number leaf is a `JsonNumber`, a reference to a definition without
 * a complete form is that definition's `Lossless` type (the definition
 * itself where it holds no number), and a reference to one with a complete
 * form is its complete form. The descriptions stay with the plain
 * definitions; each complete form carries one line naming its plain one.
 */
function completeDefinitions(definitions: Record<string, Node>): Record<string, Node> {
  /** Whether a property has a default, its own or its referenced definition's. */
  const defaulted = (member: unknown): boolean => {
    if (typeof member !== "object" || member === null) return false;
    if ("default" in member) return true;
    const { $ref: reference } = member as Node;
    return (
      typeof reference === "string" &&
      "default" in (definitions[reference.slice(REFERENCE.length)] ?? {})
    );
  };
  /** The definitions `holds` is true of, and every definition referring to one of them. */
  const closure = (holds: (definition: Node, name: string) => boolean): Set<string> => {
    const names = Object.keys(definitions);
    const found = new Set(names.filter((name) => holds(definitions[name] as Node, name)));
    for (let grown = true; grown; ) {
      grown = false;
      for (const name of names) {
        if (found.has(name)) continue;
        if ([...referencesOf(definitions[name])].some((target) => found.has(target))) {
          found.add(name);
          grown = true;
        }
      }
    }
    return found;
  };
  const completed = closure(
    (definition, name) => statesDefault(definition, defaulted) || name in STATED_DEFAULTS,
  );
  const numeric = closure(holdsNumber);

  function rewrite(value: unknown, definition: string | null): unknown {
    if (Array.isArray(value)) return value.map((item) => rewrite(item, null));
    if (typeof value !== "object" || value === null) return value;
    const node = { ...(value as Node) };
    delete node.description;
    if (typeof node.$ref === "string") {
      const target = node.$ref.slice(REFERENCE.length);
      if (completed.has(target)) {
        node.$ref = `${REFERENCE}${COMPLETE}${target}`;
      } else {
        if ("required" in node) throw new Error(`a reference to ${target} requires members`);
        return { tsType: numeric.has(target) ? `Lossless<${target}>` : target };
      }
    }
    const types = typeof node.type === "string" ? [node.type] : node.type;
    if (
      Array.isArray(types) &&
      types.some((type) => type === "number" || type === "integer") &&
      types.every((type) => typeof type === "string" && type in NUMBER_TYPES)
    ) {
      return { tsType: types.map((type) => NUMBER_TYPES[type as string]).join(" | ") };
    }
    for (const [key, member] of Object.entries(node)) {
      if (key === "properties" && typeof member === "object" && member !== null) {
        node.properties = Object.fromEntries(
          Object.entries(member as Node).map(([name, schema]) => [name, rewrite(schema, null)]),
        );
      } else if (!["default", "const", "enum"].includes(key)) {
        node[key] = rewrite(member, null);
      }
    }
    const { properties } = value as Node;
    if (typeof properties === "object" && properties !== null) {
      const withDefault = Object.entries(properties as Record<string, Node>)
        .filter(([, member]) => defaulted(member))
        .map(([key]) => key);
      const stated = definition === null ? [] : (STATED_DEFAULTS[definition] ?? []);
      const required = (node.required as string[] | undefined) ?? [];
      const added = [...withDefault, ...stated].filter((key) => !required.includes(key));
      node.required = [...required, ...added];
    }
    return node;
  }

  return Object.fromEntries(
    [...completed].map((name) => [
      `${COMPLETE}${name}`,
      {
        ...(rewrite(definitions[name], name) as Node),
        description: `\`${name}\` in the complete form: every key with a default present, every number as \`parseJson\` reads it.`,
      },
    ]),
  );
}

/**
 * Prepare a schema for the generator.
 *
 * The emitted schema keeps the source document unchanged. This view affects
 * only TypeScript generation:
 *
 * - conditionals (`if`, `then`, `else`) and an `anyOf` whose branches only
 *   require members are removed, as the generator cannot express them, and
 *   so are defaults, which would make it copy a referenced definition;
 * - a `oneOf` whose branches each state a constant and its description (the
 *   unit table) becomes an `enum` of the constants, which the generator
 *   renders as one union of literals;
 * - an object whose `oneOf` branches narrow its own properties (a
 *   coordinate's value by its number type) becomes a union of whole objects;
 * - a reference with its own description (the manifest's `meta`) becomes the
 *   one member of an `allOf`, so the property keeps the referenced type's
 *   name and its own comment instead of a renamed copy of the type;
 * - a reference that also requires members (a child timeline requiring its
 *   offset) becomes the referenced type intersected with those members;
 * - 2020-12 tuple notation is converted for the generator's older tuple
 *   reader, as `prefixItems` would otherwise become `never[]` instead of a
 *   two-item tuple.
 */
function schemaForTypes(schema: Node): Node {
  const view = JSON.parse(JSON.stringify(schema)) as Node;
  const definitions = (view.$defs ?? {}) as Record<string, Node>;
  const onlyRequires = (branch: unknown) =>
    typeof branch === "object" && branch !== null && Object.keys(branch).join() === "required";
  const onlyConstant = (branch: unknown) =>
    typeof branch === "object" &&
    branch !== null &&
    "const" in branch &&
    Object.keys(branch).every((key) => key === "const" || key === "description");

  function visit(value: unknown): void {
    if (Array.isArray(value)) {
      value.forEach(visit);
      return;
    }
    if (typeof value !== "object" || value === null) {
      return;
    }
    const node = value as Node;
    for (const keyword of ["if", "then", "else", "default"]) {
      delete node[keyword];
    }
    if (Array.isArray(node.anyOf) && node.anyOf.every(onlyRequires)) delete node.anyOf;
    if (Array.isArray(node.oneOf) && node.oneOf.every(onlyConstant)) {
      node.enum = node.oneOf.map((branch: Node) => branch.const);
      delete node.oneOf;
    }
    if (
      typeof node.properties === "object" &&
      Array.isArray(node.oneOf) &&
      node.oneOf.every((branch: Node) => !("$ref" in branch))
    ) {
      const shared = node.properties as Node;
      const required = node.required;
      node.oneOf = node.oneOf.map((branch: Node) => ({
        ...branch,
        type: "object",
        properties: { ...shared, ...(branch.properties as Node) },
        required,
      }));
      for (const keyword of ["type", "properties", "required", "discriminator"]) {
        delete node[keyword];
      }
    }
    if (typeof node.$ref === "string" && Object.keys(node).join() === "$ref,description") {
      node.allOf = [{ $ref: node.$ref }];
      delete node.$ref;
    }
    if (typeof node.$ref === "string" && Array.isArray(node.required)) {
      const target = definitions[node.$ref.replace("#/$defs/", "")] ?? {};
      const properties = (target.properties ?? {}) as Node;
      const members = node.required as string[];
      node.allOf = [
        { $ref: node.$ref },
        {
          type: "object",
          properties: Object.fromEntries(members.map((member) => [member, properties[member]])),
          required: members,
        },
      ];
      delete node.$ref;
      delete node.required;
    }
    Object.values(node).forEach(visit);
    if (Array.isArray(node.prefixItems) && node.items === false) {
      node.items = node.prefixItems;
      node.additionalItems = false;
      delete node.prefixItems;
    }
  }

  visit(view);
  return view;
}

/** Render the schema document as the constant `schema`. */
export function renderSchema(source: string): string {
  const json = JSON.stringify(readDocument(source), null, 2);
  return `${banner(source)}\nexport const schema = ${json} as const;\n`;
}

/** Render the metrics of the bundled font as a typed constant. */
export function renderFont(metricsText: string): string {
  const banner =
    "// Generated by scripts/generate.ts from fonts/dejavu-sans-2.37.metrics.json. Do not edit.";
  const json = JSON.stringify(JSON.parse(metricsText));
  return `${banner}\nimport type { FontMetrics } from "../font.js";\n\nexport const fontMetrics: FontMetrics = ${json};\n`;
}

/** Produce the generated files, keyed by file name. */
export async function generate(): Promise<Record<string, string>> {
  const source = schemaSource();
  return {
    "types.ts": await renderTypes(source),
    "schema.ts": renderSchema(source),
    "font.ts": renderFont(readFileSync(metricsPath, "utf8")),
  };
}

async function main(): Promise<void> {
  mkdirSync(generatedDirectory, { recursive: true });
  for (const [name, content] of Object.entries(await generate())) {
    writeFileSync(resolve(generatedDirectory, name), content);
    console.log(`wrote src/generated/${name}`);
  }
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
